export function ReportCard({
  report,
  lastUpdated,
  onGenerate,
  onOpenFilters,
  canExport,
  loading
}: ReportCardProps) {
  const [isGenerating, setIsGenerating] = useState(false);

  const icon = iconMap[report.icon] || iconMap['default'];

  const handleGenerate = async () => {
    console.log('[ReportCard] handleGenerate called for report:', report.id, report.name);
    console.log('[ReportCard] canExport:', canExport);
    console.log('[ReportCard] isGenerating before:', isGenerating);
    setIsGenerating(true);
    try {
      console.log('[ReportCard] Calling onGenerate with reportId:', report.id);
      await onGenerate(report.id);
      console.log('[ReportCard] onGenerate completed successfully');
    } catch (err) {
      console.error('[ReportCard] onGenerate error:', err);
    } finally {
      setIsGenerating(false);
      console.log('[ReportCard] isGenerating after finally:', isGenerating);
    }
  };

  const handleGenerateWithFilters = () => {
    onOpenFilters(report);
  };

  return (
    <div className="report-card">
      <div className="report-card-header">
        <div className="report-icon">
          {icon}
        </div>
        <div className="report-info">
          <h3 className="report-name">{report.name}</h3>
          <p className="report-description">{report.description}</p>
        </div>
      </div>

      <div className="report-card-stats">
        <div className="report-stat">
          <span className="stat-label">Records</span>
          <span className="stat-value">{report.recordCount !== undefined ? report.recordCount.toLocaleString() : '-'}</span>
        </div>
        <div className="report-stat">
          <span className="stat-label">Last Export</span>
          <span className="stat-value">{lastUpdated || 'Never'}</span>
        </div>
      </div>

      <div className="report-card-actions">
        {report.filters.length > 0 && (
          <button
            className="btn-outline"
            onClick={handleGenerateWithFilters}
            disabled={!canExport || isGenerating || loading}
          >
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <polygon points="22 3 2 3 10 12.46 10 19 14 21 14 12.46 22 3"/>
            </svg>
            Filters
          </button>
        )}
        <button
          className="btn-primary"
          onClick={handleGenerate}
          disabled={!canExport || isGenerating || loading}
        >
          {isGenerating || loading ? (
            <>
              <span className="spinner-small"></span>
              Generating...
            </>
          ) : (
            <>
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                <path d="M21 15v4a2 2 0 01-2 2H5a2 2 0 01-2-2v-4"/>
                <polyline points="7 10 12 15 17 10"/>
                <line x1="12" y1="15" x2="12" y2="3"/>
              </svg>
              Generate Report
            </>
          )}
        </button>
      </div>
    </div>
  );
}
